/**
 * Look up a glyph. Never throws: unmapped characters fall back to a blank box.
 * @param {string} ch single character (or code point)
 * @returns {string[]} 7 rows of 5 characters
 */
export function glyphFor(ch) {
  const direct = GLYPHS[ch];
  if (direct) return direct;
  const alias = FALLBACKS[ch];
  if (alias !== undefined) {
    const g = GLYPHS[alias];
    if (g) return g;
  }
  return BLANK;
}
